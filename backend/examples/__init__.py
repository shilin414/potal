# Agent Engine Examples
#
# Examples demonstrating the usage of the refactored AgentEngine
# following the claw_agent_engine design pattern.
#
# Available examples:
# - basic_chat.py: Simple chat with conversation history
# - tool_usage.py: Using tools (file read/write/search)
# - streaming_query.py: Streaming query with callbacks
# - custom_tool.py: Creating and registering custom tools
# - permission_control.py: Setting up permission controls
# - structured_output.py: Generating structured output with Pydantic
# - image_generation.py: Generating images via tools
# - video_generation.py: Generating videos via tools
# - multi_turn_agent.py: Multi-turn tool calling agent